/**
 * Converts the real Top Tin job photos (downloaded from the old site into
 * research/photos) into web-sized JPEGs in public/photos, and writes data/photos.ts.
 * Colours are described in plain words; exact Colorbond colour names are not
 * guessed from photos (owner can add them later, see docs/content-todo.md).
 */
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const SRC = "research/photos";
const OUT = "public/photos";

const photos = [
  { file: "IMG_2209-e1729428641915.png", slug: "dark-grey-roof-skylights", alt: "New dark grey Colorbond roof with skylights on a Brisbane home, trees and blue sky behind", colour: "Dark grey", hero: true },
  { file: "IMG_0601-e1729430615453.png", slug: "green-roof-crew", alt: "Top Tin roofer working on a new green Colorbond roof on a large family home", colour: "Green" },
  { file: "IMG_0592-e1729431041906.png", slug: "red-roof-crew", alt: "Roofer in hi-vis finishing a new red Colorbond roof among palm trees", colour: "Red" },
  { file: "IMG_0600-e1729433063264.png", slug: "dark-roof-skylights-wide", alt: "Wide view of a new dark Colorbond roof with skylights and valleys", colour: "Dark grey" },
  { file: "IMG_0614-e1729427940406.png", slug: "pale-green-roof", alt: "New pale green Colorbond roof with several hips and valleys on an acreage home", colour: "Pale green" },
  { file: "IMG_0615-e1729432714133.png", slug: "green-roof-valleys", alt: "Green Colorbond roof sections meeting at new valleys, with a roofer on the ridge", colour: "Green" },
  { file: "IMG_2207-e1729432674440.png", slug: "dark-grey-roof-whirlybird", alt: "Dark grey Colorbond roof with a new whirlybird vent at sunset", colour: "Dark grey" },
  { file: "IMG_0593-e1729433158831.png", slug: "light-grey-hip-roof", alt: "Light grey Colorbond hip roof with multiple sections under a blue sky", colour: "Light grey" },
  { file: "IMG_0612-e1729432777829.png", slug: "light-grey-roof-trees", alt: "Light grey Colorbond roof surrounded by gum trees", colour: "Light grey" },
  { file: "IMG_0602-e1729430259349.png", slug: "light-grey-gable-roof", alt: "Light grey Colorbond roof on a home with a decorative timber gable", colour: "Light grey" },
  { file: "IMG_0588-e1729432604286.png", slug: "light-grey-valley-roof", alt: "New light grey Colorbond roof with a valley and ridge capping", colour: "Light grey" },
  { file: "IMG_0598-e1729433109301.png", slug: "light-grey-roof-close", alt: "Close view of new light grey Colorbond sheets and flashings", colour: "Light grey" },
  { file: "IMG_0609-e1729432274519.png", slug: "dark-grey-roof-ridge", alt: "Dark grey Colorbond roof ridge and sheets with bushland behind", colour: "Dark grey" },
  { file: "IMG_0589-e1729427401119.png", slug: "grey-roof-cream-cladding", alt: "Grey Colorbond roof meeting cream wall cladding", colour: "Grey" },
  { file: "IMG_2208-e1729432649249-500-500.png", slug: "dark-grey-roof-vents", alt: "Dark grey Colorbond roof with roof vents", colour: "Dark grey" },
];

fs.mkdirSync(OUT, { recursive: true });
const out = [];
for (const p of photos) {
  const src = path.join(SRC, p.file);
  const dest = path.join(OUT, `${p.slug}.jpg`);
  const info = await sharp(src).rotate().resize({ width: 1600, height: 1600, fit: "inside", withoutEnlargement: true })
    .jpeg({ quality: 80, mozjpeg: true }).toFile(dest);
  out.push({ src: `/photos/${p.slug}.jpg`, width: info.width, height: info.height, alt: p.alt, colour: p.colour, hero: Boolean(p.hero) });
  console.log(`${dest}  ${info.width}x${info.height}  ${Math.round(info.size / 1024)}KB`);
}

const ts = `/** Real Top Tin job photos from the old site (generated by scripts/prepare-photos.mjs). */
export type Photo = { src: string; width: number; height: number; alt: string; colour: string; hero: boolean };

export const photos: Photo[] = ${JSON.stringify(out, null, 2)};

export const heroPhoto = photos.find((p) => p.hero) ?? photos[0];
`;
fs.writeFileSync("data/photos.ts", ts);
console.log("data/photos.ts written:", out.length, "photos");
